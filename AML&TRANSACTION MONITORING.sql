-- CREATE A CTE CONTAINING: CUSTOMER_ID,TRANSACTION_COUNT,TOTAL_AMOUNT,AVERAGE_AMOUNT 
-- THEN IDENTIFY CUSTOMERS WHOSE TOTAL TRANSACTION AMOUNT IS ABOVE ₹10,00,000 --

WITH TRANSACTION_SUMMARY AS (
    SELECT 
        A.CUSTOMER_ID,
        COUNT(T.TRANSACTION_AMOUNT) AS PAYMENT_COUNT,
        SUM(T.TRANSACTION_AMOUNT) AS TOTAL_PAYMENT,
        AVG(T.TRANSACTION_AMOUNT) AS AVERAGE
    FROM TRANSACTIONS T 
    JOIN ACCOUNTS A 
        ON T.ACCOUNT_ID = A.ACCOUNT_ID
    GROUP BY A.CUSTOMER_ID
    HAVING SUM(T.TRANSACTION_AMOUNT) > 1000000
)
SELECT *
FROM TRANSACTION_SUMMARY;

WITH HIGH_RISK_ANALYSIS AS (
    SELECT
        A.CUSTOMER_ID,
        SUM(T.TRANSACTION_AMOUNT) AS TOTAL_TRANSACTION_AMOUNT
    FROM TRANSACTIONS T
    JOIN ACCOUNTS A
        ON T.ACCOUNT_ID = A.ACCOUNT_ID
    GROUP BY A.CUSTOMER_ID
)

-- CREATE A CTE TO CALCULATE TOTAL TRANSACTION AMOUNT PER CUSTOMER. HIGH RISK CUSTOMERS + TOTAL TRANSACTION AMOUNT >10 LAKHS --
SELECT
    C.CUSTOMER_ID,
    CR.COUNTRY_RISK_LEVEL,
    CT.TOTAL_TRANSACTION_AMOUNT
FROM CUSTOMERS C
JOIN HIGH_RISK_ANALYSIS CT
    ON C.CUSTOMER_ID = CT.CUSTOMER_ID
JOIN COUNTRIES_RISK CR
ON C.COUNTRY=CR.COUNTRY
WHERE CR.COUNTRY_RISK_LEVEL = 'HIGH'
  AND CT.TOTAL_TRANSACTION_AMOUNT > 1000000;
  
-- CREATE A CTE CALCULATING: CUSTOMER_ID,TOTAL_ALERTS,OPEN_ALERTS,CLOSED_ALERTS THEN IDENTIFY CUSTOMERS WITH MORE THAN 5 ALERTS. --
WITH ALERT_SUMMARY AS (
    SELECT
        CUSTOMER_ID,
        COUNT(*) AS TOTAL_ALERTS,
        SUM(CASE 
                WHEN ALERT_STATUS = 'Open' THEN 1 
                ELSE 0 
            END) AS OPEN_ALERTS,
        SUM(CASE 
                WHEN ALERT_STATUS = 'Closed' THEN 1 
                ELSE 0 
            END) AS CLOSED_ALERTS
    FROM ALERTS
    GROUP BY CUSTOMER_ID
)

SELECT
    CUSTOMER_ID,
    TOTAL_ALERTS,
    OPEN_ALERTS,
    CLOSED_ALERTS
FROM ALERT_SUMMARY
WHERE TOTAL_ALERTS > 5;

