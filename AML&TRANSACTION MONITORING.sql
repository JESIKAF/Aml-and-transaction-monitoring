-- FIND CUSTOMERS WHOSE AVERAGE TRANSACTION AMOUNT IS GREATER THAN OVERALL AVERAGE TRANSACTION AOUNT --
SELECT 
    A.CUSTOMER_ID,
    AVG(T.TRANSACTION_AMOUNT) AS AVG_AMOUNT
FROM TRANSACTIONS T
JOIN ACCOUNTS A 
ON T.ACCOUNT_ID=A.ACCOUNT_ID
GROUP BY A.CUSTOMER_ID
HAVING AVG(T.TRANSACTION_AMOUNT) >
       (SELECT AVG(TRANSACTION_AMOUNT)
        FROM TRANSACTIONS);

-- FIND THE CUSTOMERS WHOSE TOTAL TRANSACTION VALUE EXCEEDS THE AVERAGE CUSTOMER TRANSACTION VALUE --
SELECT 
    A.CUSTOMER_ID,
    SUM(T.TRANSACTION_AMOUNT) AS TOTAL_AMOUNT
FROM TRANSACTIONS T
JOIN ACCOUNTS A
    ON T.ACCOUNT_ID = A.ACCOUNT_ID
GROUP BY A.CUSTOMER_ID
HAVING SUM(T.TRANSACTION_AMOUNT) >
       (
           SELECT AVG(CUSTOMER_TOTAL)
           FROM
           (
               SELECT 
                   A2.CUSTOMER_ID,
                   SUM(T2.TRANSACTION_AMOUNT) AS CUSTOMER_TOTAL
               FROM TRANSACTIONS T2
               JOIN ACCOUNTS A2
                   ON T2.ACCOUNT_ID = A2.ACCOUNT_ID
               GROUP BY A2.CUSTOMER_ID
           ) AS CUSTOMER_TOTALS
       );
       
