-- FIND CUSTOMERS WHOSE TRANSACTIONS OCCURED IN HIGH RISK COUNTRIES --
SELECT DISTINCT
    C.CUSTOMER_ID,
    T.RECEIVER_COUNTRY,
    CR.COUNTRY_RISK_LEVEL,
    CR.RISK_SCORE
FROM CUSTOMERS C
JOIN ACCOUNTS A
    ON C.CUSTOMER_ID = A.CUSTOMER_ID
JOIN TRANSACTIONS T
    ON A.ACCOUNT_ID = T.ACCOUNT_ID
JOIN COUNTRIES_RISK CR
    ON T.RECEIVER_COUNTRY = CR.COUNTRY
WHERE CR.COUNTRY_RISK_LEVEL = 'High';

-- FIND CUSTOMERS WHO HAVE HIGH TRANSACTION VALUME AND HIGH ALERT COUNT --
SELECT 
    C.CUSTOMER_ID,
    SUM(T.TRANSACTION_AMOUNT) AS TOTAL_TRANSACTION_VOLUME,
    COUNT(DISTINCT AL.ALERT_ID) AS ALERT_COUNT
FROM CUSTOMERS C
JOIN ACCOUNTS A
    ON C.CUSTOMER_ID = A.CUSTOMER_ID
JOIN TRANSACTIONS T
    ON A.ACCOUNT_ID = T.ACCOUNT_ID
LEFT JOIN ALERTS AL
    ON T.TRANSACTION_ID = AL.TRANSACTION_ID
GROUP BY C.CUSTOMER_ID
HAVING 
    SUM(T.TRANSACTION_AMOUNT) > 100000
    AND COUNT(DISTINCT AL.ALERT_ID) > 3;
    
