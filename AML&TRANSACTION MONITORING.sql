-- RANK TRANSACTION WITHIN EACH TRANSACTION CHANNEL --
SELECT  TRANSACTION_CHANNEL,
		TRANSACTION_AMOUNT,
       RANK() OVER(partition by TRANSACTION_CHANNEL
       ORDER BY TRANSACTION_AMOUNT) AS RANK_NO
FROM TRANSACTIONS;

-- RANK CUSTOMERS WITHIN EACH COUNTRY
SELECT CUSTOMER_ID,
       CITY,
       COUNTRY,
       RANK() OVER(partition by COUNTRY
       ORDER BY CUSTOMER_ID) AS COUNTRY_WISE_RANK
FROM CUSTOMERS;

-- FIND THE TOP 3 CUSTOMERS IN EACH COUNTRY BASED ON TRANSACTION AMOUNT --
SELECT *
FROM (
    SELECT 
        C.CUSTOMER_ID,
        C.COUNTRY,
        T.TRANSACTION_AMOUNT,
        DENSE_RANK() OVER (
            PARTITION BY C.COUNTRY
            ORDER BY T.TRANSACTION_AMOUNT DESC
        ) AS COUNTRY_BASED_TOP_PAYMENT
    FROM TRANSACTIONS T
    JOIN ACCOUNTS A
        ON T.ACCOUNT_ID = A.ACCOUNT_ID
    JOIN CUSTOMERS C
        ON A.CUSTOMER_ID = C.CUSTOMER_ID
) RN
WHERE COUNTRY_BASED_TOP_PAYMENT <= 3;

-- CALCULATE EACH CUSTOMER'S PERCENTAGE CONTRIBUTION TO TOTAL TRANSACTION VALUE --
SELECT
    A.CUSTOMER_ID,
    SUM(T.TRANSACTION_AMOUNT) AS TOTAL_AMOUNT,
    ROUND(
        SUM(T.TRANSACTION_AMOUNT) * 100.0 /
        SUM(SUM(T.TRANSACTION_AMOUNT)) OVER (),
        2
    ) AS PERCENTAGE_OF_TOTAL
FROM TRANSACTIONS T
JOIN ACCOUNTS A
    ON T.ACCOUNT_ID = A.ACCOUNT_ID
GROUP BY A.CUSTOMER_ID
ORDER BY TOTAL_AMOUNT DESC;

-- CALCULATE RUNNING TRANSACTION VALUE FOR EACH CUSTOMER --
SELECT 
    C.CUSTOMER_ID,
    T.TRANSACTION_DATE,
    T.TRANSACTION_AMOUNT,
    SUM(T.TRANSACTION_AMOUNT) OVER (
        PARTITION BY C.CUSTOMER_ID
        ORDER BY T.TRANSACTION_DATE
    ) AS RUNNING_TRANSACTION_VALUE
FROM TRANSACTIONS T
JOIN ACCOUNTS A
    ON T.ACCOUNT_ID = A.ACCOUNT_ID
JOIN CUSTOMERS C
    ON A.CUSTOMER_ID = C.CUSTOMER_ID
ORDER BY C.CUSTOMER_ID, T.TRANSACTION_DATE;

-- FIND THE HIGHEST TRANSACTION FOR EACH CUSTOMER --
WITH ranked_transactions AS (
    SELECT
        A.CUSTOMER_ID,
        T.TRANSACTION_ID,
        T.TRANSACTION_AMOUNT,
        ROW_NUMBER() OVER (
            PARTITION BY A.CUSTOMER_ID
            ORDER BY T.TRANSACTION_AMOUNT DESC
        ) AS RN
    FROM TRANSACTIONS T
    JOIN ACCOUNTS A
        ON T.ACCOUNT_ID = A.ACCOUNT_ID
)
SELECT
    CUSTOMER_ID,
    TRANSACTION_ID,
    TRANSACTION_AMOUNT
FROM ranked_transactions
WHERE RN = 1;

-- FIND TRANSACTIONS SIGNIFICANTLY HIGHER THAN THE CUSTOMER'S PREVIOUS TRANSACTION --
WITH transaction_analysis AS (
    SELECT
        A.CUSTOMER_ID,
        T.TRANSACTION_DATE,
        T.TRANSACTION_AMOUNT AS AMOUNT,
        LAG(T.TRANSACTION_AMOUNT) OVER (
            PARTITION BY A.CUSTOMER_ID
            ORDER BY T.TRANSACTION_DATE
        ) AS PREVIOUS_AMOUNT
    FROM TRANSACTIONS T
    JOIN ACCOUNTS A
        ON T.ACCOUNT_ID = A.ACCOUNT_ID
)
SELECT
    CUSTOMER_ID,
    TRANSACTION_DATE,
    AMOUNT,
    PREVIOUS_AMOUNT,
    AMOUNT - PREVIOUS_AMOUNT AS DIFFERENCE
FROM transaction_analysis
ORDER BY CUSTOMER_ID, TRANSACTION_DATE;